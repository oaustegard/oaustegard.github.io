"""Compile kernels/*.py to WGSL and check each kernel against CPython.

Every kernels/<demo>.py holds @kernel functions (plain Python, also runnable by
CPython) and a CHECKS dict: for each kernel, a small fixed input. build.py runs
the kernel over that input in CPython (f64), stores the result, and writes
generated/<demo>.js with the WGSL, the binding manifest, the Python source and
the check data. Each page re-runs the checks on the GPU at startup and shows
whether they agree.

    python3 build.py                  # rewrite generated/*.js
    python3 build.py --only galaxy    # one demo
    python3 build.py --check          # exit 1 if any generated file is stale

Standard library only.
"""
import argparse
import base64
import importlib.util
import inspect
import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "vendor"))
from pykernel import translate  # noqa: E402

OUT = HERE / "generated"


def f32(x):
    """Round a Python float to the nearest f32, so CPython and the GPU start equal."""
    return struct.unpack("f", struct.pack("f", x))[0]


def load(path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def reference(fn, spec, check):
    """Run fn once per invocation in CPython over the check's inputs."""
    bufs = {b.name: [f32(v) for v in check["buffers"][b.name]] for b in spec.buffers}
    scal = {u.name: (f32(check["uniforms"][u.name]) if u.type == "f32"
                     else int(check["uniforms"][u.name]))
            for u in spec.uniforms if u.name != "pk_count"}
    params = list(inspect.signature(fn).parameters)[1:]
    for gid in range(check["count"]):
        fn(gid, *[bufs[p] if p in bufs else scal[p] for p in params])
    return {name: bufs[name] for name in check["expect"]}


def build_demo(path):
    mod = load(path)
    out = {"python": path.read_text(), "kernels": {}, "arrays": []}
    pool = {}

    def ref(vals):
        """Store an array once, as base64 little-endian f32; return its index in arrays."""
        b64 = base64.b64encode(struct.pack(f"<{len(vals)}f", *vals)).decode()
        if b64 not in pool:
            pool[b64] = len(out["arrays"])
            out["arrays"].append(b64)
        return pool[b64]

    for name, check in mod.CHECKS.items():
        fn = getattr(mod, name)
        spec = translate(fn)
        missing = {b.name for b in spec.buffers} - set(check["buffers"])
        assert not missing, f"{path.name}:{name}: check has no data for buffers {missing}"
        expect = reference(fn, spec, check)
        out["kernels"][name] = {
            "manifest": spec.manifest(),
            "wgsl": spec.wgsl,
            "check": {
                "count": check["count"],
                "uniforms": check["uniforms"],
                "buffers": {k: ref([f32(v) for v in vs]) for k, vs in check["buffers"].items()},
                "expect": {k: ref(vs) for k, vs in expect.items()},
                "tol": check.get("tol", 1e-4),
                "min_frac": check.get("min_frac", 1.0),
            },
        }
    return out


def render(path):
    body = json.dumps(build_demo(path), separators=(",", ":"), sort_keys=True, allow_nan=False)
    return (f"// Generated by build.py from kernels/{path.name}. Do not edit; run python3 build.py.\n"
            f"export const DEMO = {body};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--only", help="demo name (kernels/<name>.py)")
    a = ap.parse_args()
    paths = sorted((HERE / "kernels").glob("*.py"))
    if a.only:
        paths = [p for p in paths if p.stem == a.only]
        if not paths:
            sys.exit(f"no kernels/{a.only}.py")
    OUT.mkdir(exist_ok=True)
    stale = []
    for path in paths:
        target = OUT / f"{path.stem}.js"
        text = render(path)
        if a.check:
            if not target.exists() or target.read_text() != text:
                stale.append(target.name)
            continue
        target.write_text(text)
        print(f"wrote generated/{target.name} ({len(text) // 1024} KB)")
    if stale:
        sys.exit("stale, run python3 build.py: " + ", ".join(stale))
    if a.check:
        print("generated/ is current")


if __name__ == "__main__":
    main()
